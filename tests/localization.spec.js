import { test, expect } from '@playwright/test';

const authored = 'نص كتبه المستخدم ويجب الحفاظ عليه.\nEnglish identifiers: DEMO-AR / SP-123.';
const noOverflow = async (page) => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);

test('Arabic generation, switching with edits, review, finalization and print preserve content and RTL', async ({ page }) => {
  await page.goto('/cases/new');
  await page.getByRole('button', { name: 'Switch to Arabic' }).click();
  await expect(page).toHaveTitle('هيستورا — مساحة عمل علم الأمراض');
  await page.getByRole('button', { name: 'حفظ ومتابعة' }).click();
  await expect(page.getByText('هذا الحقل مطلوب.', { exact: true })).toHaveCount(3);
  await page.getByLabel('اسم المريض').fill('مريض الاختبار');
  await page.getByLabel('رقم المريض').fill('DEMO-AR');
  await page.getByLabel('نوع العينة').fill('عينة نسيج');
  await page.getByRole('button', { name: 'حفظ ومتابعة' }).click();
  await page.getByRole('link', { name: 'المتابعة إلى التقرير' }).click();
  await page.getByRole('radio', { name: /طبيعي/ }).check();
  const editor = page.getByLabel('نص التقرير');
  await expect(editor).toHaveValue(/المريض: مريض الاختبار \(DEMO-AR\)/);
  await expect(editor).toHaveAttribute('dir', 'rtl');
  await expect(page.locator('.character-count')).toContainText('٤٠٬٠٠٠');
  await page.getByRole('button', { name: 'حفظ المسودة', exact: true }).click();
  await expect(page.getByText('حُفظت مسودة التقرير', { exact: true })).toBeVisible();
  await page.reload();
  await expect(editor).toHaveValue(/عرض تجريبي/);
  await page.getByRole('button', { name: 'Switch to English' }).click();
  await expect(page.getByLabel('Report text')).toHaveValue(/Patient: مريض الاختبار/);
  await page.getByRole('button', { name: 'Switch to Arabic' }).click();
  await expect(editor).toHaveValue(/عرض تجريبي/);
  await page.screenshot({ path: 'test-results/arabic-report-desktop.png', fullPage: true });
  await editor.fill(authored);
  await page.getByRole('button', { name: 'Switch to English' }).click();
  await expect(page.getByLabel('Report text')).toHaveValue(authored);
  await page.getByRole('button', { name: 'Switch to Arabic' }).click();
  await expect(editor).toHaveValue(authored);
  await page.getByRole('button', { name: 'حفظ المسودة', exact: true }).click();
  await expect(page.getByText('حُفظت مسودة التقرير', { exact: true })).toBeVisible();
  await expect(page.locator('[data-sonner-toaster]')).toHaveAttribute('dir', 'rtl');
  await page.reload();
  await expect(editor).toHaveValue(authored);
  await expect(page.locator('html')).toHaveAttribute('lang', 'ar');
  await page.getByRole('button', { name: 'حفظ وإرسال للمراجعة' }).click();
  await expect(page.locator('.document-report-text')).toHaveText(authored);
  await page.getByRole('button', { name: 'اعتماد التقرير', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toHaveAttribute('dir', 'rtl');
  await page.getByRole('button', { name: 'اعتماد تجريبي', exact: true }).click();
  await page.getByRole('button', { name: 'إنهاء التقرير', exact: true }).click();
  await page.getByRole('button', { name: 'إنهاء وقفل', exact: true }).click();
  await expect(page).toHaveURL(/\/final$/);
  await page.setViewportSize({ width: 390, height: 844 });
  await noOverflow(page);
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(0, { timeout: 10000 });
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: 'test-results/arabic-final-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'طباعة / حفظ PDF', exact: true }).click();
  const frame = page.frameLocator('iframe#printWindow');
  await expect(frame.locator('.report-document')).toHaveAttribute('dir', 'rtl');
  await expect(frame.locator('.report-document')).toHaveAttribute('lang', 'ar');
  await expect(frame.locator('.document-report-text')).toHaveText(authored);
  await expect(frame.locator('body')).toHaveCSS('direction', 'rtl');
  await expect(frame.locator('.document-brand')).toContainText('هيستورا');
});

test('existing demonstration data and template preview localize without changing stored data', async ({ page }) => {
  await page.goto('/cases');
  await expect(page.locator('.case-table tbody tr')).toHaveCount(6);
  const original = await page.evaluate(() => localStorage.getItem('histora:cases:v1'));
  await page.getByRole('button', { name: 'Switch to Arabic' }).click();
  await expect(page.locator('.case-table')).toContainText('أميليا هارت');
  await expect(page.locator('.case-table')).not.toContainText('Tissue specimen');
  await expect(page.locator('.heading-count')).toHaveText('٨');
  await expect(page.getByRole('button', { name: 'الصفحة التالية' }).locator('svg')).toHaveCSS('transform', 'matrix(-1, 0, 0, 1, 0, 0)');
  await page.getByLabel('البحث في الحالات').fill('أميليا');
  await expect(page.locator('.case-table tbody tr')).toHaveCount(1);
  await page.locator('.case-link').click();
  await expect(page.locator('.document-report-text')).toContainText('المريض: أميليا هارت');
  await page.getByRole('link', { name: 'قوالب التقارير', exact: true }).click();
  await expect(page.locator('.template-preview pre')).toContainText('المريض: [اسم المريض]');
  await expect(page.locator('.template-preview')).not.toContainText('Normal');
  await page.screenshot({ path: 'test-results/arabic-templates-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await noOverflow(page);
  await page.screenshot({ path: 'test-results/arabic-templates-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'فتح القائمة' }).click();
  const drawer = page.getByRole('dialog');
  await expect(drawer).toHaveAttribute('dir', 'rtl');
  const box = await drawer.boundingBox();
  expect(Math.round(box.x + box.width)).toBe(390);
  await drawer.getByRole('link', { name: 'قائمة الحالات', exact: true }).click();
  await noOverflow(page);
  expect(await page.evaluate(() => localStorage.getItem('histora:cases:v1'))).toBe(original);
  await page.getByRole('button', { name: 'Switch to English' }).click();
  await expect(page.locator('.case-table')).toContainText('Amelia Hart');
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr');
  await page.goto('/cases/demo-248/review');
  await page.getByRole('button', { name: 'Return for edits' }).click();
  await expect(page.getByLabel('Report text')).toHaveValue(/Patient: Amelia Hart/);
  await page.getByRole('button', { name: 'Switch to Arabic' }).click();
  await expect(page.getByLabel('نص التقرير')).toHaveValue(/المريض: أميليا هارت/);
  await page.getByLabel('نص التقرير').fill(authored);
  await page.getByRole('button', { name: 'Switch to English' }).click();
  await expect(page.getByLabel('Report text')).toHaveValue(authored);
});
