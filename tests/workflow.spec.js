import { test, expect } from '@playwright/test';

async function imageFile(page, name) {
  const base64 = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 48; canvas.height = 48; const context = canvas.getContext('2d'); context.fillStyle = '#785274'; context.fillRect(0, 0, 48, 48); return canvas.toDataURL('image/png').split(',')[1]; });
  return { name, mimeType: 'image/png', buffer: Buffer.from(base64, 'base64') };
}
async function intake(page, suffix) {
  await page.goto('/cases/new');
  await page.getByLabel('Patient name').fill(`Demo workflow ${suffix}`);
  await page.getByLabel('Patient ID').fill(`DEMO-${suffix}`);
  await page.getByLabel('Specimen type').fill('Demonstration tissue specimen');
  await page.getByLabel('Specimen identifier').fill(`SP-${suffix}`);
  await page.getByRole('button', { name: 'Save & continue' }).click();
  await expect(page).toHaveURL(/\/slides$/);
}
async function approveAndFinalize(page) {
  await page.getByRole('button', { name: 'Approve report', exact: true }).click();
  await page.getByRole('button', { name: 'Simulate approval', exact: true }).click();
  await expect(page.getByText('Approved and ready to finalize', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Finalize report', exact: true }).click();
  await page.getByRole('button', { name: 'Finalize & lock', exact: true }).click();
  await expect(page).toHaveURL(/\/final$/);
  await expect(page.getByRole('heading', { name: 'Read-only report' })).toBeVisible();
}
test('Normal journey: images persist, template loads, returned edits persist, final report locks and prints', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await intake(page, 'NORMAL');
  await page.getByLabel('Choose slide images').setInputFiles([await imageFile(page, 'included-slide.png'), await imageFile(page, 'excluded-slide.png')]);
  await expect(page.getByText('2 of 2 selected for the report')).toBeVisible();
  await page.getByLabel('Include excluded-slide.png in report').uncheck();
  await page.reload();
  await expect(page.getByText('1 of 2 selected for the report')).toBeVisible();
  await expect(page.locator('.slide-preview img')).toHaveCount(2);
  await page.getByRole('link', { name: 'Continue to report' }).click();
  await page.getByText('Normal', { exact: true }).click();
  await expect(page.getByLabel('Report text')).toHaveValue(/Demo workflow NORMAL/);
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.reload();
  await expect(page.getByLabel('Report text')).toHaveValue(/NORMAL REPORT WORKFLOW/);
  await page.getByRole('button', { name: 'Save & send for review' }).click();
  await expect(page).toHaveURL(/\/review$/);
  await expect(page.getByRole('button', { name: 'Print / Save as PDF' })).toHaveCount(0);
  await expect(page.locator('.document-image-grid img')).toHaveCount(1);
  await page.getByRole('button', { name: 'Return for edits' }).click();
  const text = 'DEMONSTRATION ONLY. Revised normal-path report used for workflow verification.';
  await page.getByLabel('Report text').fill(text);
  await page.getByRole('button', { name: 'Save & send for review' }).click();
  await approveAndFinalize(page);
  const finalUrl = page.url();
  await expect(page.locator('.document-report-text')).toHaveText(text);
  await page.reload();
  await expect(page.locator('.document-report-text')).toHaveText(text);
  await page.goto(finalUrl.replace('/final', '/report'));
  await expect(page).toHaveURL(/\/final$/);
  await expect(page.getByRole('textbox')).toHaveCount(0);
  await page.getByRole('button', { name: 'Print / Save as PDF' }).click();
  await expect(page.locator('iframe#printWindow')).toHaveCount(1);
  const printBody = page.frameLocator('iframe#printWindow').locator('body');
  await expect(printBody).toContainText(text);
  await expect(printBody).toContainText('included-slide.png');
  await expect(printBody).not.toContainText('excluded-slide.png');
  const pdf = await page.pdf({ path: 'test-results/normal-final-report.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true });
  expect(pdf.length).toBeGreaterThan(5000);
  expect(errors).toEqual([]);
});
test('Custom journey: incomplete draft, validation, removal, return-to-draft and approval', async ({ page }) => {
  const customText = `Custom report demonstration. No clinical findings.\n${'Nonclinical paragraph for verifying report pagination and preserved text.\n'.repeat(80)}End of demonstration report.`;
  await page.goto('/cases/new');
  await page.getByRole('button', { name: 'Save & continue' }).click();
  await expect(page.getByText('This field is required.', { exact: true })).toHaveCount(3);
  await page.getByLabel('Patient name').fill('Draft demonstration');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page).toHaveURL(/\/intake$/);
  await page.reload();
  await expect(page.getByLabel('Patient name')).toHaveValue('Draft demonstration');
  await page.getByLabel('Patient ID').fill('DEMO-CUSTOM');
  await page.getByLabel('Specimen type').fill('Demonstration specimen');
  await page.getByRole('button', { name: 'Save & continue' }).click();
  await page.getByLabel('Choose slide images').setInputFiles(await imageFile(page, 'remove-me.png'));
  await expect(page.getByText('1 of 1 selected for the report')).toBeVisible();
  await page.getByRole('button', { name: 'Remove image remove-me.png' }).click();
  await page.getByRole('button', { name: 'Remove image', exact: true }).click();
  await expect(page.getByText('No slide images yet')).toBeVisible();
  await page.getByRole('link', { name: 'Continue to report' }).click();
  await page.getByText('Custom', { exact: true }).click();
  await expect(page.getByLabel('Report text')).toHaveValue('');
  await page.getByRole('button', { name: 'Save & send for review' }).click();
  await expect(page.getByText('Enter report text before continuing to review.')).toBeVisible();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('radio', { name: /Custom/ })).toBeChecked();
  await page.getByLabel('Report text').fill(customText);
  await page.getByRole('link', { name: 'Manage slide images' }).click();
  await expect(page.getByRole('alertdialog')).toBeVisible();
  await page.getByRole('button', { name: 'Keep editing' }).click();
  await expect(page.getByLabel('Report text')).toHaveValue(customText);
  await page.getByRole('button', { name: 'Save & send for review' }).click();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await expect(page).toHaveURL(/\/cases$/);
  await page.getByLabel('Search cases').fill('DEMO-CUSTOM');
  await page.getByRole('link', { name: /^PA-/ }).click();
  await expect(page.getByLabel('Report text')).toHaveValue(customText);
  await page.getByRole('button', { name: 'Save & send for review' }).click();
  await approveAndFinalize(page);
  const pdf = await page.pdf({ path: 'test-results/custom-multipage-report.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true });
  expect((pdf.toString('latin1').match(/\/Type \/Page\b/g) || []).length).toBeGreaterThan(1);
});
